// Item is a single inventory record, mapped to the "items" table by GORM.
type Item struct {
	ID    string  `json:"id" gorm:"primaryKey"`
	Name  string  `json:"name" gorm:"not null" binding:"required"`
	Stock int     `json:"stock" gorm:"not null" binding:"gte=0"`
	Price float64 `json:"price" gorm:"not null" binding:"gte=0"`
}

// The types below only describe request/response bodies for the Swagger docs.

// ItemInput is the body for creating or updating an item (the ID is server-generated).
type ItemInput struct {
	Name  string  `json:"name" example:"USB-C Dock"`
	Stock int     `json:"stock" example:"12"`
	Price float64 `json:"price" example:"79.99"`
}

type ItemResponse struct {
	Item Item `json:"item"`
}

type ListMetadata struct {
	Limit  int `json:"limit" example:"10"`
	Offset int `json:"offset" example:"0"`
}

type ItemListResponse struct {
	Items    []Item       `json:"items"`
	Metadata ListMetadata `json:"metadata"`
}

type MessageResponse struct {
	Message string `json:"message" example:"Item deleted successfully"`
}

type ErrorResponse struct {
	Error string `json:"error" example:"Item not found"`
}

